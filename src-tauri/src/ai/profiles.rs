//! Saved LLM provider profiles, and which one is live.
//!
//! A user may keep several endpoints: a hosted key for one provider, a Gemini
//! key, and an offline runtime on localhost. Each saved profile is a name, an
//! OpenAI-compatible base URL and a model; its API key lives in the OS
//! credential store under its own slot, never in this file or the database.
//!
//! The list is stored as one JSON blob in `sync_state`. It holds no secrets, so
//! it travels with the rest of the settings; the keys stay on the device that
//! entered them.

use serde::{Deserialize, Serialize};

use crate::ai::chat::{ChatConfig, Provider};

/// How many saved endpoints the list may hold. The selector stays readable and a
/// runaway loop cannot fill the credential store.
pub const MAX_PROFILES: usize = 10;
/// Longest accepted display name.
pub const MAX_NAME: usize = 40;
/// Longest accepted model name.
pub const MAX_MODEL: usize = 120;
/// Longest accepted endpoint URL.
pub const MAX_URL: usize = 300;

/// Id of the profile created from the single setting that existed before
/// profiles were saved. Its key keeps the old credential slot.
pub const LEGACY_ID: &str = "default";

/// Why a profile could not be saved or selected.
///
/// The code is stable so the UI can translate it; the message is the English
/// fallback shown when that translation is missing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Invalid {
    /// Stable machine-readable code.
    pub code: &'static str,
    /// Human-readable fallback.
    pub message: &'static str,
}

/// The error constants, in one place so the codes cannot drift.
impl Invalid {
    const NAME_REQUIRED: Self = Self {
        code: "name_required",
        message: "a profile needs a name",
    };
    const NAME_TOO_LONG: Self = Self {
        code: "name_too_long",
        message: "the name is too long",
    };
    const URL_REQUIRED: Self = Self {
        code: "url_required",
        message: "the endpoint is empty",
    };
    const URL_INVALID: Self = Self {
        code: "url_invalid",
        message: "the endpoint is not a valid URL",
    };
    const URL_INSECURE: Self = Self {
        code: "url_insecure",
        message: "the endpoint must use https, or http on localhost",
    };
    const URL_TOO_LONG: Self = Self {
        code: "url_too_long",
        message: "the endpoint is too long",
    };
    const MODEL_REQUIRED: Self = Self {
        code: "model_required",
        message: "a profile needs a model name",
    };
    const MODEL_TOO_LONG: Self = Self {
        code: "model_too_long",
        message: "the model name is too long",
    };
    /// No profile carries the id the caller asked for.
    pub const UNKNOWN: Self = Self {
        code: "unknown_profile",
        message: "that profile no longer exists",
    };
    /// The list is at [`MAX_PROFILES`].
    pub const FULL: Self = Self {
        code: "too_many_profiles",
        message: "remove a profile before adding another",
    };
}

impl From<Invalid> for crate::commands::CommandError {
    fn from(err: Invalid) -> Self {
        Self::new(err.code, err.message)
    }
}

/// One saved endpoint.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Profile {
    /// Stable id, also the credential slot. Generated by the backend.
    pub id: String,
    /// What the user calls it.
    pub name: String,
    /// Which wire format the endpoint speaks. Profiles saved before providers
    /// existed read as `openai`, which is what they were.
    #[serde(default)]
    pub provider: Provider,
    /// OpenAI-compatible base URL, without `/chat/completions`.
    pub base_url: String,
    /// Model name as the provider spells it.
    pub model: String,
}

/// The whole list plus the active id.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, rename_all = "camelCase")]
pub struct Profiles {
    /// Id of the profile in use. Absent only while the list is empty.
    pub active: Option<String>,
    /// Saved endpoints, in the order the user added them.
    pub profiles: Vec<Profile>,
}

impl Profiles {
    /// The profile in use, if any.
    #[must_use]
    pub fn active_profile(&self) -> Option<&Profile> {
        let id = self.active.as_deref()?;
        self.profiles.iter().find(|profile| profile.id == id)
    }

    /// The profile with this id, if it exists.
    #[must_use]
    pub fn find(&self, id: &str) -> Option<&Profile> {
        self.profiles.iter().find(|profile| profile.id == id)
    }

    /// Add a profile, or replace the one with a matching id.
    ///
    /// Returns the id that was written. The first profile added becomes active,
    /// because a saved endpoint the user never selected would look broken.
    ///
    /// # Errors
    /// A broken field, or a full list.
    pub fn upsert(&mut self, input: &Input) -> Result<String, Invalid> {
        let name = normalize_name(&input.name)?;
        let base_url = normalize_base_url(&input.base_url)?;
        let model = normalize_model(&input.model)?;
        let id = if let Some(id) = input.id.as_deref() {
            if self.find(id).is_none() {
                return Err(Invalid::UNKNOWN);
            }
            id.to_owned()
        } else {
            if self.profiles.len() >= MAX_PROFILES {
                return Err(Invalid::FULL);
            }
            new_id()
        };
        let profile = Profile {
            id: id.clone(),
            name,
            provider: input.provider,
            base_url,
            model,
        };
        match self.profiles.iter_mut().find(|held| held.id == id) {
            Some(held) => *held = profile,
            None => self.profiles.push(profile),
        }
        if self.active.is_none() {
            self.active = Some(id.clone());
        }
        Ok(id)
    }

    /// Remove a profile. The active id moves to the first remaining profile.
    ///
    /// # Errors
    /// [`Invalid::UNKNOWN`] when the id is not in the list.
    pub fn remove(&mut self, id: &str) -> Result<(), Invalid> {
        let before = self.profiles.len();
        self.profiles.retain(|profile| profile.id != id);
        if self.profiles.len() == before {
            return Err(Invalid::UNKNOWN);
        }
        if self.active.as_deref() == Some(id) {
            self.active = self.profiles.first().map(|profile| profile.id.clone());
        }
        Ok(())
    }

    /// Make a profile the live one.
    ///
    /// # Errors
    /// [`Invalid::UNKNOWN`] when the id is not in the list.
    pub fn activate(&mut self, id: &str) -> Result<(), Invalid> {
        if self.find(id).is_none() {
            return Err(Invalid::UNKNOWN);
        }
        self.active = Some(id.to_owned());
        Ok(())
    }

    /// The configuration the request layer uses.
    #[must_use]
    pub fn config(&self) -> ChatConfig {
        self.active_profile()
            .map_or_else(ChatConfig::default, |profile| ChatConfig {
                provider: profile.provider,
                base_url: profile.base_url.clone(),
                model: profile.model.clone(),
            })
    }
}

/// One profile as the UI submits it. A missing id means "add a new one".
#[derive(Debug, Clone, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Input {
    /// Existing profile to edit. Absent when adding.
    pub id: Option<String>,
    /// Display name.
    pub name: String,
    /// Wire format the endpoint speaks.
    #[serde(default)]
    pub provider: Provider,
    /// Base URL, without the trailing `/chat/completions` or `/messages`.
    pub base_url: String,
    /// Model name.
    pub model: String,
}

/// Credential slot for a profile.
///
/// The migrated profile keeps the pre-profile slot, so a key the user already
/// stored is still found without touching the credential store.
#[must_use]
pub fn key_slot(id: &str) -> &str {
    if id == LEGACY_ID { "" } else { id }
}

/// Whether an id is safe to use as a credential slot.
///
/// Android stores each secret as `<name>.enc` in a private directory, so an id
/// that could contain a path separator must never reach the store.
#[must_use]
pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 40
        && id
            .chars()
            .all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '-')
}

/// A generated profile id.
fn new_id() -> String {
    uuid::Uuid::new_v4().to_string()
}

/// Validate a display name.
///
/// # Errors
/// A message when it is empty or too long.
pub fn normalize_name(raw: &str) -> Result<String, Invalid> {
    let name = raw.trim();
    if name.is_empty() {
        return Err(Invalid::NAME_REQUIRED);
    }
    if name.chars().count() > MAX_NAME {
        return Err(Invalid::NAME_TOO_LONG);
    }
    Ok(name.to_owned())
}

/// Validate an endpoint URL: https anywhere, plain http only on this machine.
///
/// # Errors
/// A message when the URL is unusable or would send a key in clear text.
pub fn normalize_base_url(raw: &str) -> Result<String, Invalid> {
    let url = raw.trim().trim_end_matches('/');
    if url.is_empty() {
        return Err(Invalid::URL_REQUIRED);
    }
    if url.chars().count() > MAX_URL {
        return Err(Invalid::URL_TOO_LONG);
    }
    if reqwest::Url::parse(url).is_err() {
        return Err(Invalid::URL_INVALID);
    }
    if !url.starts_with("https://") && !crate::commands::ai::is_local_endpoint(url) {
        // Plain http would send the key in clear text over a network. A loopback
        // address is allowed because a local model runtime is the offline case.
        return Err(Invalid::URL_INSECURE);
    }
    Ok(url.to_owned())
}

/// Validate a model name.
///
/// # Errors
/// A message when it is empty or too long.
pub fn normalize_model(raw: &str) -> Result<String, Invalid> {
    let model = raw.trim();
    if model.is_empty() {
        return Err(Invalid::MODEL_REQUIRED);
    }
    if model.chars().count() > MAX_MODEL {
        return Err(Invalid::MODEL_TOO_LONG);
    }
    Ok(model.to_owned())
}

/// The list after migrating the single pre-profile setting.
///
/// The old setting had a URL and a model but no name, so the host becomes the
/// name: `api.openai.com` reads better in a selector than "Profile 1".
#[must_use]
pub fn from_legacy(config: &ChatConfig) -> Profiles {
    let name = reqwest::Url::parse(&config.base_url)
        .ok()
        .and_then(|url| url.host_str().map(str::to_owned))
        .map_or_else(|| "Default".to_owned(), |host| host.replace("www.", ""));
    Profiles {
        active: Some(LEGACY_ID.to_owned()),
        profiles: vec![Profile {
            id: LEGACY_ID.to_owned(),
            name,
            provider: config.provider,
            base_url: config.base_url.trim_end_matches('/').to_owned(),
            model: config.model.clone(),
        }],
    }
}

/// Where the saved list lives in `sync_state`.
const KEY: &str = "llm.profiles";

/// The live endpoint plus its key, as one request needs them.
#[derive(Debug, Clone)]
pub struct Resolved {
    /// The active profile, absent while nothing is saved.
    pub profile: Option<Profile>,
    /// Base URL and model the request layer uses.
    pub config: ChatConfig,
    /// The stored key for that profile, when there is one.
    pub key: Option<crate::secrets::ChatApiKey>,
}

/// Read the saved list, migrating the older single setting on first read.
///
/// A malformed blob falls back to the old setting rather than emptying the list:
/// a profile the user typed is worth more than the certainty of a parse.
pub async fn load(pool: &sqlx::SqlitePool) -> Profiles {
    let found: Result<Option<(String,)>, _> =
        sqlx::query_as("SELECT value FROM sync_state WHERE key = 'llm.profiles'")
            .fetch_optional(pool)
            .await;
    if let Ok(Some((json,))) = found
        && let Ok(profiles) = serde_json::from_str::<Profiles>(&json)
        && !profiles.profiles.is_empty()
    {
        return profiles;
    }
    let legacy = crate::commands::ai::read_legacy_config(pool).await;
    let migrated = from_legacy(&legacy);
    // Best effort: a failed write leaves the migration to the next read, and the
    // caller still gets a usable answer now.
    let _ = store(pool, &migrated).await;
    migrated
}

/// Write the list.
///
/// # Errors
/// Serialization or database failure.
pub async fn store(pool: &sqlx::SqlitePool, profiles: &Profiles) -> Result<(), crate::db::DbError> {
    let json = serde_json::to_string(profiles)
        .map_err(|err| crate::db::DbError::Corrupt(err.to_string()))?;
    sqlx::query(
        "INSERT INTO sync_state (key, value) VALUES (?1, ?2) \
         ON CONFLICT(key) DO UPDATE SET value = excluded.value",
    )
    .bind(KEY)
    .bind(json)
    .execute(pool)
    .await?;
    Ok(())
}

/// The active profile and its key, ready to send a request.
pub async fn resolve(pool: &sqlx::SqlitePool) -> Resolved {
    let profiles = load(pool).await;
    let profile = profiles.active_profile().cloned();
    let config = profiles.config();
    let key = match profile.as_ref().map(|held| key_slot(&held.id).to_owned()) {
        // Android's credential bridge must not block the UI thread.
        Some(slot) => {
            tauri::async_runtime::spawn_blocking(move || crate::secrets::load_chat_key(&slot))
                .await
                .ok()
                .and_then(Result::ok)
        }
        None => None,
    };
    Resolved {
        profile,
        config,
        key,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn input(name: &str, url: &str, model: &str) -> Input {
        Input {
            id: None,
            name: name.into(),
            provider: Provider::OpenAi,
            base_url: url.into(),
            model: model.into(),
        }
    }

    fn code(result: Result<impl Sized, Invalid>) -> &'static str {
        result.err().map_or("ok", |err| err.code)
    }

    #[test]
    fn the_first_saved_endpoint_becomes_active_and_later_ones_do_not_steal_it() {
        let mut profiles = Profiles::default();
        let first = profiles
            .upsert(&input(
                "OpenAI",
                "https://api.openai.com/v1/",
                "gpt-4o-mini",
            ))
            .expect("save");
        assert_eq!(profiles.active.as_deref(), Some(first.as_str()));
        profiles
            .upsert(&input("Lokal", "http://127.0.0.1:11434/v1", "qwen3"))
            .expect("save");
        assert_eq!(profiles.active.as_deref(), Some(first.as_str()));
        // A trailing slash is stripped once, so the request URL never doubles it.
        assert_eq!(profiles.profiles[0].base_url, "https://api.openai.com/v1");
    }

    #[test]
    fn editing_keeps_the_id_and_the_active_choice() {
        let mut profiles = Profiles::default();
        let id = profiles
            .upsert(&input(
                "Gemini",
                "https://generativelanguage.googleapis.com/v1beta/openai/",
                "gemini-2.5-flash",
            ))
            .expect("save");
        let mut edit = input(
            "Gemini 2.5",
            "https://generativelanguage.googleapis.com/v1beta/openai",
            "gemini-2.5-pro",
        );
        edit.id = Some(id.clone());
        let saved = profiles.upsert(&edit).expect("save");
        assert_eq!(saved, id);
        assert_eq!(profiles.profiles.len(), 1);
        let held = profiles.active_profile().expect("active");
        assert_eq!(held.name, "Gemini 2.5");
        assert_eq!(held.model, "gemini-2.5-pro");
    }

    #[test]
    fn deleting_the_active_endpoint_falls_back_to_another() {
        let mut profiles = Profiles::default();
        let first = profiles
            .upsert(&input("A", "https://a.example/v1", "m"))
            .expect("save");
        let second = profiles
            .upsert(&input("B", "https://b.example/v1", "m"))
            .expect("save");
        profiles.activate(&second).expect("activate");
        profiles.remove(&second).expect("delete");
        assert_eq!(profiles.active.as_deref(), Some(first.as_str()));
        profiles.remove(&first).expect("delete");
        assert_eq!(profiles.active, None);
        // Compared against the default so a failure prints what was left.
        assert_eq!(profiles.profiles, Profiles::default().profiles);
    }

    #[test]
    fn unknown_ids_are_refused_instead_of_silently_ignored() {
        let mut profiles = Profiles::default();
        assert_eq!(code(profiles.activate("nope")), "unknown_profile");
        assert_eq!(code(profiles.remove("nope")), "unknown_profile");
        let mut edit = input("A", "https://a.example/v1", "m");
        edit.id = Some("nope".into());
        assert_eq!(code(profiles.upsert(&edit)), "unknown_profile");
        // Compared against the default so a failure prints what was left.
        assert_eq!(profiles.profiles, Profiles::default().profiles);
    }

    #[test]
    fn the_list_is_capped() {
        let mut profiles = Profiles::default();
        for index in 0..MAX_PROFILES {
            profiles
                .upsert(&input(&format!("P{index}"), "https://a.example/v1", "m"))
                .expect("save");
        }
        assert_eq!(
            code(profiles.upsert(&input("Over", "https://a.example/v1", "m"))),
            "too_many_profiles"
        );
        // Editing an existing entry still works at the cap.
        let mut edit = input("P0 renamed", "https://a.example/v1", "m");
        edit.id = Some(profiles.profiles[0].id.clone());
        assert!(profiles.upsert(&edit).is_ok());
    }

    #[test]
    fn an_endpoint_over_plain_http_is_refused_unless_it_is_local() {
        assert_eq!(
            code(normalize_base_url("http://example.com/v1")),
            "url_insecure"
        );
        assert_eq!(
            code(normalize_base_url("http://192.168.1.10:11434/v1")),
            "url_insecure"
        );
        assert_eq!(
            normalize_base_url("http://127.0.0.1:1234/v1"),
            Ok("http://127.0.0.1:1234/v1".into())
        );
        assert_eq!(
            normalize_base_url("https://generativelanguage.googleapis.com/v1beta/openai/"),
            Ok("https://generativelanguage.googleapis.com/v1beta/openai".into())
        );
        assert_eq!(code(normalize_base_url("   ")), "url_required");
        assert_eq!(code(normalize_base_url("not a url")), "url_invalid");
    }

    #[test]
    fn a_profile_needs_a_name_and_a_model() {
        assert_eq!(code(normalize_name("  ")), "name_required");
        assert_eq!(code(normalize_model(" ")), "model_required");
        assert_eq!(
            code(normalize_name(&"x".repeat(MAX_NAME + 1))),
            "name_too_long"
        );
        assert_eq!(
            code(normalize_model(&"x".repeat(MAX_MODEL + 1))),
            "model_too_long"
        );
    }

    #[test]
    fn the_migrated_profile_is_named_after_its_host_and_keeps_the_old_key_slot() {
        let legacy = ChatConfig::default();
        let profiles = from_legacy(&legacy);
        assert_eq!(profiles.active.as_deref(), Some(LEGACY_ID));
        assert_eq!(profiles.profiles[0].name, "api.openai.com");
        assert_eq!(profiles.profiles[0].base_url, "https://api.openai.com/v1");
        assert_eq!(key_slot(LEGACY_ID), "");
        // Every generated profile gets its own slot.
        assert_eq!(
            key_slot("6f1e6b0c-0000-4000-8000-000000000000"),
            "6f1e6b0c-0000-4000-8000-000000000000"
        );
    }

    #[test]
    fn ids_are_restricted_to_what_a_credential_slot_can_hold() {
        assert!(valid_id("6f1e6b0c-0000-4000-8000-000000000000"));
        assert!(valid_id(LEGACY_ID));
        assert!(!valid_id("../../etc/passwd"));
        assert!(!valid_id("UPPER"));
        assert!(!valid_id(""));
    }

    #[tokio::test]
    async fn the_old_single_setting_becomes_one_saved_profile() {
        let db = crate::db::Db::open_memory().await.expect("open");
        let legacy = ChatConfig {
            provider: Provider::OpenAi,
            base_url: "https://generativelanguage.googleapis.com/v1beta/openai/".into(),
            model: "gemini-2.5-flash".into(),
        };
        sqlx::query("INSERT INTO sync_state (key, value) VALUES ('chat.config', ?1)")
            .bind(serde_json::to_string(&legacy).expect("json"))
            .execute(db.pool())
            .await
            .expect("seed");

        let migrated = load(db.pool()).await;
        assert_eq!(migrated.active.as_deref(), Some(LEGACY_ID));
        assert_eq!(migrated.profiles.len(), 1);
        // The trailing slash is gone, so the request URL is not doubled.
        assert_eq!(
            migrated.profiles[0].base_url,
            "https://generativelanguage.googleapis.com/v1beta/openai"
        );
        // The migration is written, so the next read is not another legacy path.
        let stored: (String,) =
            sqlx::query_as("SELECT value FROM sync_state WHERE key = 'llm.profiles'")
                .fetch_one(db.pool())
                .await
                .expect("stored");
        assert!(stored.0.contains("gemini-2.5-flash"));
    }

    #[tokio::test]
    async fn a_saved_list_survives_a_reload_and_a_broken_blob_falls_back() {
        let db = crate::db::Db::open_memory().await.expect("open");
        let mut saved = Profiles::default();
        let gemini = saved
            .upsert(&input(
                "Gemini",
                "https://generativelanguage.googleapis.com/v1beta/openai",
                "gemini-2.5-flash",
            ))
            .expect("save");
        saved
            .upsert(&input("Lokal", "http://127.0.0.1:11434/v1", "qwen3"))
            .expect("save");
        store(db.pool(), &saved).await.expect("store");

        let reloaded = load(db.pool()).await;
        assert_eq!(reloaded, saved);
        assert_eq!(reloaded.active.as_deref(), Some(gemini.as_str()));
        assert_eq!(reloaded.config().model, "gemini-2.5-flash");

        sqlx::query("UPDATE sync_state SET value = 'not json' WHERE key = 'llm.profiles'")
            .execute(db.pool())
            .await
            .expect("break");
        let recovered = load(db.pool()).await;
        assert_eq!(recovered.active.as_deref(), Some(LEGACY_ID));
        assert_eq!(recovered.profiles.len(), 1);
    }

    #[test]
    fn the_active_configuration_falls_back_to_the_default_when_empty() {
        let profiles = Profiles::default();
        assert_eq!(profiles.config(), ChatConfig::default());
        let mut profiles = Profiles::default();
        let id = profiles
            .upsert(&input(
                "Gemini",
                "https://generativelanguage.googleapis.com/v1beta/openai",
                "gemini-2.5-flash",
            ))
            .expect("save");
        assert_eq!(profiles.active.as_deref(), Some(id.as_str()));
        assert_eq!(profiles.config().model, "gemini-2.5-flash");
    }
}
